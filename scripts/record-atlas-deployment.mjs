import {readFile,writeFile,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url);
const json=async p=>JSON.parse(await readFile(new URL(p,root),'utf8'));
const [id,url]=process.argv.slice(2);
if(!/^[a-f0-9-]{36}$/.test(id??'')||url!==`https://${id.slice(0,8)}.roda-kekacauan.pages.dev`)throw new Error('Supply the verified Cloudflare deployment ID and URL.');
const [verification,hosting,assets,selection]=await Promise.all(['preview/atlas-verification.json','hosting/cloudflare.json','preview/atlas-live-assets.json','preview/atlas-live-selection.json'].map(json));
const artifactSha256=createHash('sha256').update(await readFile(new URL('roda-kekacauan-deploy.zip',root))).digest('hex').toUpperCase();
if(artifactSha256!==verification.uploadArtifact.sha256)throw new Error('Artifact changed since verification.');
if(assets.results.length!==9||assets.results.some(r=>r.status!==200||!r.matchesLocal))throw new Error('Live asset verification is incomplete.');
const publicUrl='https://roda-kekacauan.pages.dev/atlas/';
if(selection.libraryUrl!==publicUrl||selection.libraryVersion!==verification.libraryVersion||selection.references.length!==4||selection.references.some(r=>!r.depictionContext?.userApproved||r.image.plateId!=='hero-origin-corrections-01'))throw new Error('Live reference export mismatch.');
await stat(new URL('preview/atlas-hero-source-live.jpg',root));
const verifiedAtUtc=new Date().toISOString();
const date=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Bangkok',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
const deployment={id,url,productionUrl:publicUrl,environment:'production',branch:'main',method:'wrangler-direct-upload',date,verifiedAtUtc,artifactSha256,filesInOutput:verification.uploadArtifact.fileCount,staticFiles:558,newStaticFilesUploaded:544,cachedStaticFiles:14,atlasImageFiles:64,libraryVersion:verification.libraryVersion};
verification.publicationStatus='deployed-and-browser-verified';
delete verification.publicationBlocker;
verification.deployment=deployment;
verification.publicUrl=publicUrl;
verification.liveVerification={date,verifiedAtUtc,liveAssetHashMatches:9,browserSearch:'passed',correctedHeroImages:'passed',sourceNotesAndLinks:'passed',referenceSelectionAndExport:'passed',exportLibraryUrl:selection.libraryUrl,screenshot:'preview/atlas-hero-source-live.jpg',assetReport:'preview/atlas-live-assets.json',exportReport:'preview/atlas-live-selection.json'};
verification.imageAudit.localOnly=false;
verification.imageAudit.localScreenshot=verification.imageAudit.screenshot;
verification.imageAudit.screenshot=verification.liveVerification.screenshot;
hosting.previousDeploymentId=hosting.latestDeploymentId===id?hosting.previousDeploymentId:hosting.latestDeploymentId;
hosting.latestDeploymentId=id;
hosting.latestDeploymentUrl=url;
hosting.latestDeploymentDate=date;
hosting.latestUploadMethod='wrangler-direct-upload';
hosting.uploadedFileCount=verification.uploadArtifact.fileCount;
hosting.artifactSha256=artifactSha256;
hosting.verifiedAtUtc=verifiedAtUtc;
hosting.status='deployed-and-browser-verified';
hosting.atlasEntryCount=713;
hosting.atlasImageFiles=64;
hosting.heroReferencesReviewed=110;
hosting.heroImagesCorrected=40;
hosting.credentialsStoredInProject=false;
hosting.uploaderCredentialsStorage='Encrypted user-profile file with key in Windows Credential Manager';
hosting.atlasDeployments??=[];
if(!hosting.atlasDeployments.some(d=>d.id===id))hosting.atlasDeployments.push({...deployment,purpose:'visual-atlas-and-whole-roster-origin-corrections',heroImagesCorrected:40});
await writeFile(new URL('preview/atlas-verification.json',root),JSON.stringify(verification,null,2)+'\n');
await writeFile(new URL('hosting/cloudflare.json',root),JSON.stringify(hosting,null,2)+'\n');
console.log(JSON.stringify({status:verification.publicationStatus,...deployment}));
