import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, cp, writeFile, readFile, stat, rm, readdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import vm from 'node:vm';
import { demos } from '../scripts/examples.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
test('build creates standalone published profiles, strips private fields and removes unpublished pages/assets',async()=>{
  const taskRoot=await mkdtemp(path.join(os.tmpdir(),'roda-wiki-test-'));
  try {
    for (const dir of ['web','scripts','data']) await mkdir(path.join(taskRoot,dir),{recursive:true});
    await cp(path.join(root,'web'),path.join(taskRoot,'web'),{recursive:true});
    await cp(path.join(root,'scripts'),path.join(taskRoot,'scripts'),{recursive:true});
    const wikiFile=path.join(taskRoot,'data/wiki.json');
    const wiki=JSON.parse(await readFile(path.join(root,'data/wiki.json'),'utf8'));
    wiki.entries.find(e=>e.sources.length).sources[0].privateNotes='PRIVATE_SENTINEL';wiki.entries[0].privateNotes='PRIVATE_SENTINEL';(wiki.entries[0].provenance ??= {}).localPath='PRIVATE_SENTINEL';
    await writeFile(wikiFile,JSON.stringify(wiki));
    const real=structuredClone(demos[0]);real.id='test-only';real.name='Test $& <name>';real.status='published';
    real.publication={tiktokUrl:'https://www.tiktok.com/@test/video/123456789',publishedAt:'2026-10-10'};
    real.image.src='assets/test-only.svg';real.privateNotes='PRIVATE_SENTINEL';real.stats.speed.privateNotes='PRIVATE_SENTINEL';
    await cp(path.join(taskRoot,'web/assets/demo-garuda.svg'),path.join(taskRoot,'web/assets/test-only.svg'));
    const draft=structuredClone(real);draft.id='draft-test';draft.episode=2;draft.status='draft';draft.image.src='assets/draft-only.svg';
    await cp(path.join(taskRoot,'web/assets/demo-garuda.svg'),path.join(taskRoot,'web/assets/draft-only.svg'));
    const archiveFile=path.join(taskRoot,'data/characters.json');
    await writeFile(archiveFile,JSON.stringify({schemaVersion:1,characters:[real,draft]}));
    execFileSync(process.execPath,['scripts/build.mjs'],{cwd:taskRoot});
    const js=await readFile(path.join(taskRoot,'dist/catalog.js'),'utf8');
    const scope={window:{}};vm.runInNewContext(js,scope);
    assert.equal(scope.window.WIKI_CATALOG.characters.length,1);
    assert.equal(scope.window.WIKI_CATALOG.demos.length,3);
    assert.ok(!js.includes('PRIVATE_SENTINEL'));
    assert.equal(scope.window.WIKI_CATALOG.wiki.length,wiki.entries.length);
    const tuyul=await readFile(path.join(taskRoot,'dist/wiki/tuyul/index.html'),'utf8');
    assert.ok(tuyul.includes('<base href="../../">'));
    assert.ok(tuyul.includes('Tuyul adalah makhluk kecil'));
    assert.ok(tuyul.includes('https://mandarin.fbs.unesa.ac.id/'));
    assert.ok(tuyul.includes('wiki/power-nyolong/'));
    assert.ok(tuyul.includes('<h2>Lore singkat</h2>'));
    assert.ok(tuyul.includes('Adaptasi dunia Roda Kekacauan'));
    assert.ok(tuyul.includes('<h2>Inspirasi &amp; rujukan</h2>'));
    assert.ok(tuyul.includes('Sosok kecil ini muncul dalam cerita'));
    assert.equal(scope.window.WIKI_CATALOG.wiki.filter(e=>e.lore&&e.inspiration).length,469);
    const vending=await readFile(path.join(taskRoot,'dist/wiki/power-isekai-cheat-vending/index.html'),'utf8');
    assert.ok(vending.includes('Reborn as a Vending Machine, I Now Wander the Dungeon.'));
    assert.ok(vending.includes('https://yenpress.com/series/'));
    assert.ok(!tuyul.includes('PRIVATE_SENTINEL'));
    const abyssal=await readFile(path.join(taskRoot,'dist/wiki/demon/index.html'),'utf8');
    for(const [id,label]of [['demon-lord','Raja Iblis Agung'],['iblis','Iblis'],['fallen-angel','Fallen Angel'],['setan','Setan'],['pendosa','Pendosa']])assert.ok(abyssal.includes(`<a class="wiki-link" href="wiki/${id}/">${label}</a>`));
    const iblis=await readFile(path.join(taskRoot,'dist/wiki/iblis/index.html'),'utf8');
    assert.ok(iblis.includes('href="wiki/pool-power-demonic/"'));
    const html=await readFile(path.join(taskRoot,'dist/karakter/test-only/index.html'),'utf8');
    assert.ok(html.includes('<base href="../../">'));
    assert.ok(html.includes('Test $&amp; &lt;name&gt;'));
    const home=await readFile(path.join(taskRoot,'dist/index.html'),'utf8');
    assert.ok(home.includes('Test $&amp; &lt;name&gt;'));
    const releases=[...home.matchAll(/(?:src|href)="(?:[a-z-]+\.js|style\.css)\?v=([a-f0-9]{12})"/g)].map(m=>m[1]);
    assert.equal(releases.length,6);assert.equal(new Set(releases).size,1);
    assert.ok(tuyul.includes(`app.js?v=${releases[0]}`));
    const assets=await readdir(path.join(taskRoot,'dist/assets'));
    assert.ok(assets.includes('test-only.svg'));assert.ok(!assets.includes('draft-only.svg'));
    assert.ok(!(await stat(path.join(taskRoot,'dist/karakter/draft-test')).catch(()=>null)));
    real.status='draft';await writeFile(archiveFile,JSON.stringify({schemaVersion:1,characters:[real,draft]}));
    wiki.entries=wiki.entries.filter(e=>e.id!=='tuyul');
    wiki.entries.forEach(e=>e.related=e.related.filter(id=>id!=='tuyul'));
    await writeFile(wikiFile,JSON.stringify(wiki));
    execFileSync(process.execPath,['scripts/build.mjs'],{cwd:taskRoot});
    const changedHome=await readFile(path.join(taskRoot,'dist/index.html'),'utf8');
    assert.ok(!changedHome.includes(`app.js?v=${releases[0]}`));
    assert.ok(!(await stat(path.join(taskRoot,'dist/karakter/test-only')).catch(()=>null)));
    assert.ok(!(await readdir(path.join(taskRoot,'dist/assets'))).includes('test-only.svg'));
    assert.ok(!(await stat(path.join(taskRoot,'dist/wiki/tuyul')).catch(()=>null)));
  } finally {
    const resolved=path.resolve(taskRoot),tempBase=path.resolve(os.tmpdir());
    if (!resolved.startsWith(tempBase+path.sep) || !path.basename(resolved).startsWith('roda-wiki-test-')) throw new Error('Unsafe test cleanup target.');
    await rm(resolved,{recursive:true,force:true});
  }
});
